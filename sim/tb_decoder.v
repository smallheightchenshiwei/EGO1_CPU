
`timescale 1ns / 1ps

module tb_decoder;

reg [31:0] inst;

wire [4:0] rd;
wire [4:0] rj;
wire [4:0] rk;

wire [4:0] raddr1;
wire [4:0] raddr2;
wire [4:0] waddr;

wire [31:0] imm;

wire [3:0] alu_ctrl;
wire alu_src_imm;

wire [1:0] wb_sel;
wire reg_we;

wire mem_we;
wire mem_re;

wire [2:0] branch_type;
wire valid;

integer count;
integer errors;

// =====================================================
// Decoder实例
// =====================================================

decoder uut (
    .inst(inst),
    .rd(rd),
    .rj(rj),
    .rk(rk),
    .raddr1(raddr1),
    .raddr2(raddr2),
    .waddr(waddr),
    .imm(imm),
    .alu_ctrl(alu_ctrl),
    .alu_src_imm(alu_src_imm),
    .wb_sel(wb_sel),
    .reg_we(reg_we),
    .mem_we(mem_we),
    .mem_re(mem_re),
    .branch_type(branch_type),
    .valid(valid)
);

// =====================================================
// 测试任务
// =====================================================

task check;
    input [60:0] expected;
    begin
        #1;
        count = count + 1;

        if ({
            raddr1, raddr2, waddr,
            imm, alu_ctrl, alu_src_imm,
            wb_sel, reg_we, mem_we, mem_re,
            branch_type, valid
        } !== expected) begin

            errors = errors + 1;

            $display("ERROR: Test %0d", count);
            $display("INST     = %h", inst);
            $display("Expected = %h", expected);

            $display("Actual   = %h", {
                raddr1, raddr2, waddr,
                imm, alu_ctrl, alu_src_imm,
                wb_sel, reg_we, mem_we, mem_re,
                branch_type, valid
            });

        end
        else begin
            $display("PASS: Test %0d", count);
        end
    end
endtask

